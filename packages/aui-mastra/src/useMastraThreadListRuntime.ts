"use client";

/**
 * Full thread-list runtime for Mastra Memory.
 *
 * Wraps `useRemoteThreadListRuntime` from assistant-ui with a
 * `RemoteThreadListAdapter` backed by the Mastra memory API.  Handles:
 *
 * - Thread list (list, fetch, rename, delete)
 * - Lazy thread creation on first message send (`initialize`)
 * - Per-thread chat runtime with history loading
 * - The `__LOCALID_*` race condition (same fix as `/chat` v1)
 *
 * Returns an `AssistantRuntime` that powers both `<Thread />` and
 * `<ThreadListPrimitive.*>` components from assistant-ui.
 *
 * @example
 * ```tsx
 * import { useMastraThreadListRuntime } from "@repo/aui-mastra";
 *
 * const runtime = useMastraThreadListRuntime({
 *   baseUrl: "http://localhost:4111",
 *   agentId: "weatherAgent",
 *   resourceId: "user-123",
 * });
 *
 * <AssistantRuntimeProvider runtime={runtime}>
 *   <SidebarProvider>
 *     <ThreadListSidebar />   // uses ThreadListPrimitive
 *     <SidebarInset>
 *       <Thread />
 *     </SidebarInset>
 *   </SidebarProvider>
 * </AssistantRuntimeProvider>
 * ```
 */

import { useChat } from "@ai-sdk/react";
import type { RemoteThreadListAdapter } from "@assistant-ui/react";
import { useAuiState, useRemoteThreadListRuntime } from "@assistant-ui/react";
import { AssistantChatTransport, useAISDKRuntime } from "@assistant-ui/react-ai-sdk";
import { createAssistantStream } from "assistant-stream";
import { useMemo, useRef } from "react";
import { createHistoryAdapter } from "./createHistoryAdapter";
import { mastraFetch, normaliseHeaders, resolveHeaders } from "./internal/fetch";
import type { HeadersConfig, MastraThread } from "./types";

// ---------------------------------------------------------------------------
// Config
// ---------------------------------------------------------------------------

/** Configuration for `useMastraThreadListRuntime`. */
export type MastraThreadListConfig = {
  /** Base URL of the Mastra server (e.g. "http://localhost:4111"). */
  baseUrl: string;
  /** Agent ID — required by the Mastra memory API on every endpoint. */
  agentId: string;
  /** Resource ID identifying the current user. */
  resourceId: string;
  /** Headers for authentication (e.g. JWT Bearer token). */
  headers?: HeadersConfig;
  /**
   * Path prefix for the chatRoute endpoint.
   * The full URL is `${baseUrl}${chatPath}/${agentId}`.
   * @default "/chat"
   */
  chatPath?: string;
  /**
   * Optional summarizer agent for AI-generated thread titles.
   *
   * When enabled, the first user message is sent to
   * `POST /api/agents/{agentId}/generate` and the response text is used
   * as the thread title.
   *
   * When omitted or `enabled: false`, titles are generated by truncating
   * the first user message to 60 characters.
   *
   * @example
   * ```ts
   * titleAgent: {
   *   enabled: true,
   *   agentId: "summarizerAgent",
   * }
   * ```
   */
  titleAgent?: {
    /** Whether to use the summarizer agent. @default false */
    enabled: boolean;
    /** REST route key of the summarizer agent (e.g. `"summarizerAgent"`). */
    agentId: string;
  };
};

// ---------------------------------------------------------------------------
// Thread ID resolution  (same fix as /chat v1 — see AGENTS.md)
// ---------------------------------------------------------------------------
// assistant-ui assigns temporary `__LOCALID_xxx` IDs to new threads.
// `initialize()` creates the real server-side thread, but
// `prepareSendMessagesRequest` can fire BEFORE `initialize()` completes.
// We store pending promises so the request callback can await them.

function resolveThreadId(threadId: string, map: Map<string, string>): string {
  return map.get(threadId) ?? threadId;
}

async function resolveThreadIdAsync(
  threadId: string,
  map: Map<string, string>,
  pending: Map<string, Promise<string>>,
): Promise<string> {
  const p = pending.get(threadId);
  if (p) return p;
  return map.get(threadId) ?? threadId;
}

// ---------------------------------------------------------------------------
// Imperative Mastra memory API functions
// ---------------------------------------------------------------------------

async function apiListThreads(
  baseUrl: string,
  agentId: string,
  resourceId: string,
  headers?: HeadersConfig,
): Promise<MastraThread[]> {
  const result = await mastraFetch<{ threads: MastraThread[] }>(
    `${baseUrl}/api/memory/threads?agentId=${encodeURIComponent(agentId)}&resourceId=${encodeURIComponent(resourceId)}`,
    headers,
  );
  return result.threads;
}

async function apiCreateThread(
  baseUrl: string,
  agentId: string,
  resourceId: string,
  headers?: HeadersConfig,
): Promise<MastraThread> {
  return mastraFetch<MastraThread>(
    `${baseUrl}/api/memory/threads?agentId=${encodeURIComponent(agentId)}`,
    headers,
    { method: "POST", body: JSON.stringify({ resourceId }) },
  );
}

async function apiFetchThread(
  baseUrl: string,
  agentId: string,
  threadId: string,
  headers?: HeadersConfig,
): Promise<MastraThread> {
  return mastraFetch<MastraThread>(
    `${baseUrl}/api/memory/threads/${threadId}?agentId=${encodeURIComponent(agentId)}`,
    headers,
  );
}

async function apiRenameThread(
  baseUrl: string,
  agentId: string,
  threadId: string,
  title: string,
  headers?: HeadersConfig,
): Promise<void> {
  await mastraFetch(
    `${baseUrl}/api/memory/threads/${threadId}?agentId=${encodeURIComponent(agentId)}`,
    headers,
    { method: "PATCH", body: JSON.stringify({ title }) },
  );
}

async function apiDeleteThread(
  baseUrl: string,
  agentId: string,
  threadId: string,
  headers?: HeadersConfig,
): Promise<void> {
  await mastraFetch(
    `${baseUrl}/api/memory/threads/${threadId}?agentId=${encodeURIComponent(agentId)}`,
    headers,
    { method: "DELETE" },
  );
}

// ---------------------------------------------------------------------------
// RemoteThreadListAdapter factory
// ---------------------------------------------------------------------------

function createThreadListAdapter(
  configRef: { current: MastraThreadListConfig },
  threadIdMap: Map<string, string>,
  pendingInits: Map<string, Promise<string>>,
): RemoteThreadListAdapter {
  const cfg = () => configRef.current;

  return {
    async list() {
      const { baseUrl, agentId, resourceId, headers } = cfg();
      const threads = await apiListThreads(baseUrl, agentId, resourceId, headers);
      return {
        threads: threads.map((t) => ({
          status: "regular" as const,
          remoteId: t.id,
          title: t.title,
          externalId: undefined,
        })),
      };
    },

    async initialize(localThreadId: string) {
      // Guard: already completed
      const existing = threadIdMap.get(localThreadId);
      if (existing) return { remoteId: existing, externalId: undefined };

      // Guard: already in-flight
      const inflight = pendingInits.get(localThreadId);
      if (inflight) {
        const remoteId = await inflight;
        return { remoteId, externalId: undefined };
      }

      // Create the server-side thread
      const { baseUrl, agentId, resourceId, headers } = cfg();
      const promise = apiCreateThread(baseUrl, agentId, resourceId, headers).then((thread) => {
        threadIdMap.set(localThreadId, thread.id);
        pendingInits.delete(localThreadId);
        return thread.id;
      });
      pendingInits.set(localThreadId, promise);

      const remoteId = await promise;
      return { remoteId, externalId: undefined };
    },

    async fetch(threadId: string) {
      const { baseUrl, agentId, headers } = cfg();
      const thread = await apiFetchThread(baseUrl, agentId, threadId, headers);
      return {
        status: "regular" as const,
        remoteId: thread.id,
        title: thread.title,
        externalId: undefined,
      };
    },

    async rename(threadId: string, newTitle: string) {
      const { baseUrl, agentId, headers } = cfg();
      await apiRenameThread(baseUrl, agentId, threadId, newTitle, headers);
    },

    async archive(threadId: string) {
      const { baseUrl, agentId, headers } = cfg();
      await apiDeleteThread(baseUrl, agentId, threadId, headers);
    },

    async unarchive() {
      // Mastra doesn't support unarchive — threads are hard-deleted
    },

    async delete(threadId: string) {
      const { baseUrl, agentId, headers } = cfg();
      await apiDeleteThread(baseUrl, agentId, threadId, headers);
    },

    async generateTitle(threadId: string, messages: readonly unknown[]) {
      // Extract the first user message text.
      type MessageLike = {
        role?: string;
        content?: string | ReadonlyArray<{ type?: string; text?: string }>;
      };
      const firstUserMsg = (messages as MessageLike[]).find((m) => m.role === "user");
      const rawContent = firstUserMsg?.content;
      const text =
        typeof rawContent === "string"
          ? rawContent
          : Array.isArray(rawContent)
            ? rawContent
                .filter((p) => p.type === "text" && p.text)
                .map((p) => p.text)
                .join(" ")
            : "";

      if (!text) {
        return createAssistantStream((controller) => {
          controller.close();
        });
      }

      const { baseUrl, agentId, headers, titleAgent } = cfg();
      let title: string;

      if (titleAgent?.enabled && titleAgent.agentId) {
        // Call the summarizer agent to generate a concise title
        try {
          const resolved = await resolveHeaders(headers);
          const res = await fetch(
            `${baseUrl}/api/agents/${encodeURIComponent(titleAgent.agentId)}/generate`,
            {
              method: "POST",
              headers: { "Content-Type": "application/json", ...resolved },
              body: JSON.stringify({
                messages: [{ role: "user", content: text }],
              }),
            },
          );
          if (res.ok) {
            const data = (await res.json()) as { text?: string };
            title = data.text?.trim() || text.slice(0, 60).trim();
          } else {
            // Agent call failed — fall back to truncation
            title = text.slice(0, 60).trim();
          }
        } catch {
          // Network error — fall back to truncation
          title = text.slice(0, 60).trim();
        }
      } else {
        // No summarizer agent — truncate the first user message
        title = text.slice(0, 60).trim();
      }

      title = title || "New Chat";

      // Persist the title (fire-and-forget)
      apiRenameThread(baseUrl, agentId, threadId, title, headers).catch(() => {});

      return createAssistantStream((controller) => {
        controller.appendText(title);
        controller.close();
      });
    },
  };
}

// ---------------------------------------------------------------------------
// Per-thread runtime hook factory
// ---------------------------------------------------------------------------
// Defined as a factory so the returned function has a stable identity and
// can close over the refs without being recreated on every render.

function createThreadRuntimeHook(
  configRef: { current: MastraThreadListConfig },
  threadIdMap: Map<string, string>,
  pendingInits: Map<string, Promise<string>>,
) {
  return function useThreadRuntime() {
    const cfg = configRef.current;
    const threadId = useAuiState((s) => s.threadListItem.id);
    const chatUrl = `${cfg.baseUrl}${cfg.chatPath ?? "/chat"}/${cfg.agentId}`;

    const transport = useMemo(
      () =>
        new AssistantChatTransport({
          api: chatUrl,
          headers: normaliseHeaders(cfg.headers),
          prepareSendMessagesRequest: async (options) => {
            const resolved = await resolveThreadIdAsync(threadId, threadIdMap, pendingInits);
            return {
              ...options,
              body: {
                ...options.body,
                messages: options.messages,
                memory: {
                  thread: resolved,
                  resource: cfg.resourceId,
                },
              },
            };
          },
        }),
      [threadId, chatUrl],
    );

    const chat = useChat({ id: threadId, transport });

    const resolvedId = resolveThreadId(threadId, threadIdMap);
    const historyAdapter = useMemo(
      () =>
        createHistoryAdapter({
          threadId: resolvedId,
          baseUrl: cfg.baseUrl,
          agentId: cfg.agentId,
          headers: cfg.headers,
        }),
      [resolvedId],
    );

    return useAISDKRuntime(chat, { adapters: { history: historyAdapter } });
  };
}

