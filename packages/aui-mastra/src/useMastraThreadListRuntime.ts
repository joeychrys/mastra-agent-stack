/**
 * Full thread-list runtime for a Mastra agent with memory.
 *
 * Combines `useRemoteThreadListRuntime` with a Mastra-backed
 * adapter and per-thread chat runtime.  The returned `AssistantRuntime`
 * drives both the thread list sidebar (`ThreadListPrimitive`) and the
 * active conversation (`Thread`).
 */
export function useMastraThreadListRuntime(config: MastraThreadListConfig) {
  const configRef = useRef(config);
  configRef.current = config;

  const threadIdMap = useRef(new Map<string, string>()).current;
  const pendingInits = useRef(new Map<string, Promise<string>>()).current;

  const runtimeHook = useMemo(
    () => createThreadRuntimeHook(configRef, threadIdMap, pendingInits),
    [threadIdMap, pendingInits],
  );

  const adapter = useMemo(
    () => createThreadListAdapter(configRef, threadIdMap, pendingInits),
    [threadIdMap, pendingInits],
  );

  return useRemoteThreadListRuntime({
    runtimeHook,
    adapter,
  });
}
